def times(n, day_breaks=None):
    """Bar open times: consecutive M5 bars; day_breaks = {bar index: whole days added from there on}."""
    out = []
    extra = 0
    for i in range(n):
        if day_breaks and i in day_breaks:
            extra = day_breaks[i]
        out.append(T0 + i * PERIOD + extra * 86400)
    return out


