def _build(steps, start=2000.0, wick=0.1):
    out = []
    c = start
    for s in steps:
        o = c
        c = round(o + s, 2)
        out.append((o, round(max(o, c) + wick, 2), round(min(o, c) - wick, 2), c))
    return out


