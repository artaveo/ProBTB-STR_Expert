def mirror(ohlc, m=4000.0):
    """Short mirror: price x -> m - x (highs and lows swap)."""
    return [(round(m - o, 2), round(m - l, 2), round(m - h, 2), round(m - c, 2)) for o, h, l, c in ohlc]
